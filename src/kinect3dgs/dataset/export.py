"""Undistort, lay out, describe and atomically commit a dataset (FR-5, FR-7, FR-8)."""
from __future__ import annotations

import json
import os
import shutil
from datetime import datetime, timezone
from pathlib import Path

import pycolmap

README = """COLMAP dataset generated by kinect3dgs (AKS-003)

  images/            undistorted photos (PNG)
  sparse/0/          cameras.bin, images.bin, points3D.bin  (PINHOLE camera, one pose per photo, first point cloud)
  dataset.json       provenance: sessions, selected frames, camera, SfM stats, metric scale

Use it with a 3D Gaussian Splatting tool:

  OpenSplat (verified):   opensplat {folder} -n 30000 -o splat.ply
  Nerfstudio, gsplat, Postshot: read COLMAP datasets too, but have NOT been tested with this folder yet.
    Point them at this folder (images/ + sparse/0/) as their COLMAP input.

Scale: {scale_line}
"""


def export_dataset(rec: pycolmap.Reconstruction, images_dir: Path, work: Path, tmp_out: Path, text: bool) -> None:
    model_dir = work / "final_model"
    if model_dir.exists():
        shutil.rmtree(model_dir)
    model_dir.mkdir(parents=True)
    rec.write(model_dir)
    und = work / "undistorted"
    if und.exists():
        shutil.rmtree(und)
    pycolmap.undistort_images(und, model_dir, images_dir)
    if tmp_out.exists():
        shutil.rmtree(tmp_out)
    (tmp_out / "sparse" / "0").mkdir(parents=True)
    shutil.move(str(und / "images"), str(tmp_out / "images"))
    for f in (und / "sparse").glob("*.bin"):
        shutil.move(str(f), str(tmp_out / "sparse" / "0" / f.name))
    if text:
        pycolmap.Reconstruction(tmp_out / "sparse" / "0").write_text(str(tmp_out / "sparse" / "0"))


def write_metadata(tmp_out: Path, meta: dict, folder_name: str) -> None:
    (tmp_out / "dataset.json").write_text(json.dumps(meta, indent=2, default=str))
    sc = meta.get("metric_scale", {})
    line = (f"metric (1 unit = 1 metre; scale {sc['scale_to_meters']:.4f} applied from Kinect depth)"
            if sc.get("applied") else f"arbitrary units (metric scale not applied: {sc.get('reason', 'disabled')})")
    (tmp_out / "README.txt").write_text(README.format(folder=folder_name, scale_line=line).replace("{folder}", folder_name))


def commit(tmp_out: Path, out: Path) -> None:
    """Replace `out` with `tmp_out` (rename); the old folder is restored if anything fails."""
    old = None
    if out.exists():
        old = out.with_name(out.name + f".old-{os.getpid()}")
        out.rename(old)
    try:
        tmp_out.rename(out)
    except Exception:
        if old is not None:
            old.rename(out)
        raise
    if old is not None:
        shutil.rmtree(old, ignore_errors=True)


def now_utc() -> str:
    return datetime.now(timezone.utc).isoformat()
